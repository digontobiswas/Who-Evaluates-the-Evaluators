"""Held-out closed-loop scenarios: navtest scenes that are not in NavHard, for BridgeSim.

Protocol (fixed on 1 Nov 2026, before any of these scenes was converted or scored):

* Candidates are the navtest tokens of BridgeSim's own navtest scene filter, minus every token of
  the NavHard filter and of BridgeSim's 421-scene list.
* They are ranked by SHA-256("<salt>|<token>") and the first ``n_candidates`` form the filter
  given to BridgeSim's converter. The converter drops tokens without 20 s of logged future.
* The held-out set is the first ``count`` converted candidates in rank order (all of them if
  fewer converted). Nothing about a scene except whether it converted decides its membership.

Degradations and benign perturbations are validated on all 421 NavHard scenes; every evaluator is
then measured on the held-out scenes only (wete.analysis --heldout).

    python -m wete.closed_loop.heldout --navtest-filter <bridgesim>/converters/openscene/filter/navtest.yaml \\
        --exclude-filter <bridgesim>/converters/openscene/filter/navhard_two_stage.yaml \\
        --exclude-list <bridgesim>/converters/openscene/converted_list/navhard421.txt \\
        --out-filter configs/bridgesim/navtest_heldout_filter.yaml \\
        --out-list configs/bridgesim/navtest_heldout_candidates.txt
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
from typing import Dict, Iterable, List, Sequence

import yaml

SALT = "wete-heldout-2026-11-01"
N_CANDIDATES = 700
COUNT = 420          # same size as NavHard, so a GPU job has the same length as before


def _token(s: str) -> str:
    s = str(s).strip()
    return s[3:] if s.startswith("sd_") else s


def rank(tokens: Iterable[str], salt: str = SALT) -> List[str]:
    """Tokens ordered by SHA-256(salt|token); duplicates removed."""
    uniq = sorted({_token(t) for t in tokens})
    return sorted(uniq, key=lambda t: hashlib.sha256(f"{salt}|{t}".encode()).hexdigest())


def build_filter(navtest: Dict, exclude: Iterable[str], salt: str = SALT,
                 n_candidates: int = N_CANDIDATES) -> Dict:
    """BridgeSim scene filter: navtest's settings and logs, tokens = ranked candidates."""
    excluded = {_token(t) for t in exclude}
    pool = [t for t in navtest["tokens"] if _token(t) not in excluded]
    candidates = rank(pool, salt)[:n_candidates]
    out = {k: v for k, v in navtest.items() if k not in ("tokens",)}
    out["tokens"] = candidates
    return out


def select(candidates: Sequence[str], converted: Iterable[str], count: int = COUNT) -> List[str]:
    """First `count` converted candidates in rank order, as BridgeSim scenario names (sd_<token>)."""
    done = {_token(c) for c in converted}
    return [f"sd_{t}" for t in candidates if _token(t) in done][:count]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--navtest-filter", required=True)
    ap.add_argument("--exclude-filter", action="append", default=[])
    ap.add_argument("--exclude-list", action="append", default=[])
    ap.add_argument("--salt", default=SALT)
    ap.add_argument("--n-candidates", type=int, default=N_CANDIDATES)
    ap.add_argument("--out-filter", required=True)
    ap.add_argument("--out-list", required=True)
    a = ap.parse_args(argv)

    navtest = yaml.safe_load(Path(a.navtest_filter).read_text())
    exclude: List[str] = []
    for f in a.exclude_filter:
        exclude += yaml.safe_load(Path(f).read_text()).get("tokens") or []
    for f in a.exclude_list:
        exclude += Path(f).read_text().split()
    flt = build_filter(navtest, exclude, a.salt, a.n_candidates)
    header = (f"# Held-out navtest scenes for BridgeSim, generated by wete.closed_loop.heldout\n"
              f"# salt={a.salt} n_candidates={a.n_candidates}; navtest tokens {len(navtest['tokens'])}, "
              f"excluded {len(set(map(_token, exclude)))} NavHard tokens. Do not edit by hand.\n")
    Path(a.out_filter).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out_filter).write_text(header + yaml.safe_dump(flt, sort_keys=False))
    Path(a.out_list).write_text("\n".join(flt["tokens"]) + "\n")
    print(f"[heldout] {len(flt['tokens'])} candidates -> {a.out_filter}, {a.out_list}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
